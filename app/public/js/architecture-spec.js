// 匯流排：同一區出去、進同一個方塊的線，畫成一條主幹。**links 不動**——那裡仍是一條一條的
// 事實（誰連誰、什麼關係），匯流排只改「怎麼畫」，hover 打亮與測試都還是看 links。
//
// 為什麼要合：程式碼倉庫那三格各自拉線到測試區時，三條線在同一條走廊裡上下穿插，而它們要講的
// 是同一件事——「這三樣東西湊成測試區」。合完那一區從 5 條線變 2 條，順帶消掉一個拓樸上
// 閃不掉的交叉（核心→測試區 與 GitHub→AI 代理 原本必須交換上下順序）。
//
// 代價：線上的標籤變成合寫的。個別差異（核心是開容器時自帶、另兩個是唯讀掛入）改寫在方塊
